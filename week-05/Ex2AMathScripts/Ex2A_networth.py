# Net worth = Assets - Debts
# Assets: cash, savings, investments, property, vehicles, etc.
# Debts: credit cards, loans, mortgages, etc.
assets_cash = 100
assets_savings = 1000
assets_investments = 5000
debts_credit = 1000
debts_bills = 1000
total_assets = assets_cash + assets_savings + assets_investments
total_debts = debts_credit + debts_bills
net_worth = total_assets - total_debts
print(f"Your total assets are {total_assets}")
print(f"Your total debts are {total_debts}")
print(f"Your net worth is {net_worth}")

